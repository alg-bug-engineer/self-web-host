import { test, expect } from '@playwright/test'
test('series opens and server totals agree across browsers', async ({ page, browser }) => {
 await page.goto('/planet')
 await page.getByRole('link', { name: '开始学习 →' }).click()
 await expect(page.locator('#series-stats')).toContainText('次观看')
 await page.goto('/planet/series/01.html')
 await expect(page.getByRole('button', {name:/^点赞/})).toBeVisible()
 await page.getByRole('button', { name: /^点赞/ }).click()
 await expect(page.getByRole('button', {name:/^点赞/})).toHaveAttribute('aria-pressed','true')
 const context=await browser.newContext()
 const response=await context.request.post('/api/planet-series',{data:{id:'01',action:'read'}})
 expect(response.ok()).toBeTruthy()
 expect((await response.json()).likes).toBeGreaterThanOrEqual(1)
 await expect(page.locator('body')).toHaveCSS('user-select','none')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:`/tmp/planet-series-${test.info().project.name}.png`})
 await context.close()
})

test('share copies episode URL', async ({page, context}) => {
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 await page.goto('/planet/series/02.html')
 await page.getByRole('button',{name:'分享：复制本期网址'}).click()
 await expect(page.getByRole('status').filter({hasText:'网址已复制'})).toBeVisible()
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toContain('/planet/series/02.html')
 await expect(page.locator('#series-stats')).toHaveCSS('position','static')
})
